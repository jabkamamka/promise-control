@dataclass
class PromiseType:
    code: str
    title: str
    description: str
    keywords: list[str] = field(default_factory=list)
    examples: list[str] = field(default_factory=list)
    is_builtin: bool = False
    priority: int = 78

    @property
    def normalized_keywords(self) -> list[str]:
        return [normalize_text(k) for k in self.keywords if k and k.strip()]

    def example_tokens(self) -> set[str]:
        tokens: set[str] = set()
        for ex in self.examples:
            tokens.update(t for t in normalize_text(ex).replace(",", " ").split() if len(t) > 2)
        tokens.update(t for t in normalize_text(self.description).replace(",", " ").split() if len(t) > 3)
        return tokens
